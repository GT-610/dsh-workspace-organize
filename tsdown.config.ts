/**
 * Build the two halves of the plugin.
 *
 * The Host half is one bundled ES module the Cordis Loader imports through
 * `exports["."]`.
 *
 * The Client half must be a closure-factory artifact: the DSH web shell loads
 * it as a script and expects it to call `window.__ModuleLoader__.load({ id,
 * factory })`, where the factory receives the module table's `require` and
 * returns the plugin definition. tsdown emits the CommonJS chunk, and the
 * banner/footer close it inside that factory — the same shape the shipped
 * client bundles and the third-party plugins in the ecosystem publish. Using
 * the chunk addons (rather than a transform plugin) keeps the emitted source map
 * exact.
 */
import { defineConfig } from 'tsdown'

/** Package name, which is also the loader id the client bundle registers. */
const CLIENT_ID = 'dsh-workspace-organize'

/**
 * `PLATFORM_MODULES` from the web shell (`@deepseek-ai/dsh-client-web`), in the
 * same order. These are seeded into the frozen module table before any plugin
 * runs, so a client bundle must require — never inline — them, and a baseline
 * entry must not be repeated in `dsh.client.external`.
 */
const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  'zod',
  '@tanstack/react-virtual',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

export default defineConfig([
  {
    name: 'host',
    entry: { index: 'src/index.ts' },
    outDir: 'dist',
    format: 'esm',
    platform: 'node',
    target: 'node22',
    // `index.js` / `index.d.ts`, not the fixed `.mjs` / `.d.mts` pair.
    fixedExtension: false,
    dts: true,
    clean: true,
    sourcemap: true,
  },
  {
    name: 'client',
    entry: { client: 'src/client/index.tsx' },
    outDir: 'dist',
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    deps: { neverBundle: PLATFORM_MODULES },
    dts: false,
    clean: false,
    sourcemap: true,
    banner: [
      '// Generated by tsdown; do not edit. See tsdown.config.ts for the wrapper.',
      'window.__ModuleLoader__.load({',
      `\tid: ${JSON.stringify(CLIENT_ID)},`,
      '\tfactory(require) {',
      '\t\tconst module = { exports: {} };',
      '\t\tconst exports = module.exports;',
      '',
    ].join('\n'),
    footer: [
      '',
      '\t\treturn module.exports;',
      '\t},',
      '});',
      '',
    ].join('\n'),
  },
])
